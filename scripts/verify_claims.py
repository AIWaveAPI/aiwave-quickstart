#!/usr/bin/env python3
"""Verify tracked route, family and video counts against the live endpoint.

This scans the ACTUAL TEXT of the repos and reports which file and line is
stale, so a drifting number can be fixed in one command:

    python3 scripts/sync_claims.py

Usage:
    python3 scripts/verify_claims.py [--repo-root PATH] [--catalog-json PATH]

--catalog-json  lets CI or an offline machine verify against a saved copy of
                the public endpoint response. Default fetches the live URL.
Only PATTERNS matches in SCAN_EXT files are checked; this is not a price audit.
Exit code 0 = tracked counts match. 1 = stale tracked count(s). 2 = no data.
No API key required — this reads only public data.
"""
import argparse
import json
import os
import re
import sys
import urllib.request
from datetime import datetime, timezone

ENDPOINT = "https://aiwave.live/api/pricing"
CHINESE_PREFIXES = ["deepseek", "glm", "kimi", "qwen", "doubao", "step",
                    "xiaomi", "minimax", "kling", "wan3"]
VIDEO_MARKERS = ["kling", "seedance", "hailuo", "wan3.0-video", "vidu"]

# (regex, group with the number, expected key)
# Deliberately specific: "13 routes on the public rate card" inside a sentence
# about VIDEO must not be read as a claim about the TOTAL route count.
PATTERNS = [
    (re.compile(r"(\d+)\s+routes?\s+(?:on|in)\s+the\s+public\s+rate\s+card"), 1, "routes"),
    (re.compile(r"(\d+)\s+public\s+routes"), 1, "routes"),
    (re.compile(r"(\d+)\s+AI\s+routes"), 1, "routes"),
    (re.compile(r"(\d+)\s+Chinese\s+(?:AI\s+|model\s+)?families"), 1, "families"),
    (re.compile(r"(\d+)\s+families"), 1, "families"),
    (re.compile(r"(\d+)\s+(?:public\s+)?video[-\s](?:generation\s+)?routes"), 1, "video"),
    (re.compile(r"(?:video(?:%20|[-\s]))?routes?-(\d+)-"), 1, "video"),  # shields.io badge (URL-encoded or plain)
    (re.compile(r"families\s*\+\s*(\d+)\s+video"), 1, "video"),
]

SKIP_DIRS = {".git", "node_modules", "build", "dist", "__pycache__", "pkg", "secrets"}
SCAN_EXT = {".md", ".py", ".toml", ".json", ".mjs", ".js", ".yml", ".yaml"}
# CHANGELOG is history; MODEL_REFERENCE is regenerated by gen_model_reference.py.
SKIP_FILES = {"verify_claims.py", "sync_claims.py", "catalog-claims.json",
              "CHANGELOG.md", "MODEL_REFERENCE.md", "test_error_handlers.py",
              "test_aiwave_setup.py", "test_claims_tools.py"}
HISTORY_HINT = re.compile(r"verified\s+20\d\d-|as\s+of\s+20\d\d-|was\s+\"|dated\s+20\d\d")


def load_catalog(path):
    if path:
        with open(path, encoding="utf-8") as f:
            return json.load(f)
    req = urllib.request.Request(ENDPOINT, headers={"User-Agent": "aiwave-verify/2.0"})
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.loads(r.read().decode("utf-8"))


def live_numbers(data):
    models = data.get("models") or data.get("data") or []
    families = set()
    for m in models:
        name = (m.get("model_name") or m.get("id") or "").lower()
        for p in CHINESE_PREFIXES:
            if name.startswith(p):
                families.add("qwen" if p == "qwen" else p)
                break
    video = [m for m in models
             if any(k in (m.get("model_name") or m.get("id") or "").lower()
                    for k in VIDEO_MARKERS)]
    return {"routes": len(models), "families": len(families), "video": len(video),
            "pricing_version": str(data.get("pricing_version") or "?")[:16]}


def iter_files(root):
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS]
        for fn in filenames:
            if os.path.splitext(fn)[1].lower() in SCAN_EXT:
                yield os.path.join(dirpath, fn)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo-root", default=os.path.abspath(
        os.path.join(os.path.dirname(__file__), "..")))
    ap.add_argument("--catalog-json", default=None)
    args = ap.parse_args()

    print(f"AIWave published-claims verification — {datetime.now(timezone.utc):%Y-%m-%d %H:%M UTC}")
    print(f"Source: {args.catalog_json or ENDPOINT}")
    try:
        data = load_catalog(args.catalog_json)
    except Exception as e:
        print(f"ERROR: cannot load catalog: {e}", file=sys.stderr)
        return 2
    models = data.get("models") or data.get("data") or []
    if not models:
        print("ERROR: empty catalog — refusing to validate against nothing.", file=sys.stderr)
        return 2

    live = live_numbers(data)
    print(f"Live: routes={live['routes']} families={live['families']} "
          f"video={live['video']} version={live['pricing_version']}…\n")

    mismatches, scanned = [], 0
    for path in iter_files(args.repo_root):
        if os.path.basename(path) in SKIP_FILES:
            continue
        try:
            text = open(path, encoding="utf-8", errors="ignore").read()
        except OSError:
            continue
        scanned += 1
        seen = set()
        for lineno, line in enumerate(text.splitlines(), 1):
            if HISTORY_HINT.search(line):
                continue
            for pat, gi, key in PATTERNS:
                for m in pat.finditer(line):
                    claimed = int(m.group(gi))
                    if claimed == live[key]:
                        continue
                    tag = (lineno, key, claimed)
                    if tag in seen:
                        continue
                    seen.add(tag)
                    rel = os.path.relpath(path, args.repo_root)
                    mismatches.append((rel, lineno, key, claimed, live[key], line.strip()[:96]))

    print(f"Scanned {scanned} files under {args.repo_root}")
    print("-" * 76)
    if mismatches:
        print(f"RESULT: MISMATCH — {len(mismatches)} stale claim(s)\n")
        for rel, lineno, key, claimed, actual, snippet in sorted(mismatches):
            print(f"  {rel}:{lineno}  [{key}] published={claimed} live={actual}")
            print(f"      > {snippet}")
        print("\nFix all with:  python3 scripts/sync_claims.py --repo-root <root>")
        return 1
    print("RESULT: ALL TRACKED CATALOG COUNTS MATCH")
    return 0


if __name__ == "__main__":
    sys.exit(main())

