#!/usr/bin/env python3
"""Re-sync every published catalog number with the live public endpoint.

The catalog drifts (models are added/retired weekly). Hand-editing seven
files each time is how stale numbers survive. This script finds every claim
pattern in the repos and rewrites ONLY the number, keeping the surrounding
text intact.

Usage:
    python3 scripts/sync_claims.py --repo-root <root> [--catalog-json PATH]
    python3 scripts/sync_claims.py --repo-root <root> --dry-run

Always run verify_claims.py afterwards, review the git diff, then commit.
Never point this at the production server or a directory containing secrets.
"""
import argparse
import json
import os
import re
import sys
import urllib.request
from datetime import datetime, timezone

ENDPOINT = "https://aiwave.live/api/pricing"
CHINESE_PREFIXES = ["deepseek", "glm", "kimi", "qwen", "doubao", "step",
                    "xiaomi", "minimax", "kling", "wan3"]
VIDEO_MARKERS = ["kling", "seedance", "hailuo", "wan3.0-video", "vidu"]

# (compiled pattern, group holding the number, key). Must mirror verify_claims.py.
PATTERNS = [
    (re.compile(r"(\d+)\s+routes?\s+(?:on|in)\s+the\s+public\s+rate\s+card"), 1, "routes"),
    (re.compile(r"(\d+)\s+public\s+routes"), 1, "routes"),
    (re.compile(r"(\d+)\s+AI\s+routes"), 1, "routes"),
    (re.compile(r"(\d+)\s+Chinese\s+(?:AI\s+|model\s+)?families"), 1, "families"),
    (re.compile(r"(\d+)\s+families"), 1, "families"),
    (re.compile(r"(\d+)\s+(?:public\s+)?video[-\s](?:generation\s+)?routes"), 1, "video"),
    (re.compile(r"(?:video(?:%20|[-\s]))?routes?-(\d+)-"), 1, "video"),
    (re.compile(r"families\s*\+\s*(\d+)\s+video"), 1, "video"),
]

SKIP_DIRS = {".git", "node_modules", "build", "dist", "__pycache__", "pkg", "secrets"}
SCAN_EXT = {".md", ".py", ".toml", ".json", ".mjs", ".js", ".yml", ".yaml"}
# Historical records and generated artifacts must not be rewritten here.
# CHANGELOG = history; MODEL_REFERENCE = regenerated by gen_model_reference.py.
SKIP_FILES = {"verify_claims.py", "sync_claims.py", "catalog-claims.json",
              "CHANGELOG.md", "MODEL_REFERENCE.md", "test_error_handlers.py",
              "test_aiwave_setup.py"}
# Lines describing a dated historical observation, not a current claim.
HISTORY_HINT = re.compile(r"verified\s+20\d\d-|as\s+of\s+20\d\d-|was\s+\"|dated\s+20\d\d")


def load_catalog(path):
    if path:
        with open(path, encoding="utf-8") as f:
            return json.load(f)
    req = urllib.request.Request(ENDPOINT, headers={"User-Agent": "aiwave-sync/1.0"})
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.loads(r.read().decode("utf-8"))


def live_numbers(data):
    models = data.get("models") or data.get("data") or []
    families = set()
    for m in models:
        name = (m.get("model_name") or m.get("id") or "").lower()
        for p in CHINESE_PREFIXES:
            if name.startswith(p):
                families.add("qwen" if p == "qwen" else p)
                break
    video = [m for m in models
             if any(k in (m.get("model_name") or m.get("id") or "").lower()
                    for k in VIDEO_MARKERS)]
    return {"routes": len(models), "families": len(families), "video": len(video),
            "pricing_version": str(models[0].get("pricing_version", "?"))[:16] if models else "?"}


def replace_line(line, live):
    """Replace only the numeric token of each claim; never touch other text."""
    edits = []
    out = line
    # Apply longest matches first by collecting (start, end, group-start, group-end, value)
    spans = []
    for pat, gi, key in PATTERNS:
        for m in pat.finditer(line):
            spans.append((m.start(gi), m.end(gi), live[key]))
    # Deduplicate overlapping spans, prefer the first pattern that matched.
    chosen, used = [], set()
    for start, end, value in sorted(spans, key=lambda x: (-x[0], x[1])):
        if any(s < end and start < e for s, e in used):
            continue
        used.add((start, end))
        chosen.append((start, end, value))
    # Rewrite from right to left so offsets stay valid.
    for start, end, value in sorted(chosen, key=lambda x: -x[0]):
        old = line[start:end]
        if old == str(value):
            continue
        edits.append((old, value))
        out = out[:start] + str(value) + out[end:]
    return out, edits


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo-root", required=True)
    ap.add_argument("--catalog-json", default=None)
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    data = load_catalog(args.catalog_json)
    live = live_numbers(data)
    print(f"Live catalog: routes={live['routes']} families={live['families']} "
          f"video={live['video']} version={live['pricing_version']}…")
    print(f"{'DRY RUN — nothing written' if args.dry_run else 'Writing changes'}\n")

    changed_files = 0
    total_edits = 0
    for dirpath, dirnames, filenames in os.walk(args.repo_root):
        dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS]
        for fn in filenames:
            if os.path.splitext(fn)[1].lower() not in SCAN_EXT or fn in SKIP_FILES:
                continue
            path = os.path.join(dirpath, fn)
            try:
                text = open(path, encoding="utf-8").read()
            except (OSError, UnicodeDecodeError):
                continue
            lines = text.splitlines(keepends=True)
            new_lines, file_edits = [], []
            for i, raw in enumerate(lines):
                line = raw.rstrip("\r\n")
                if HISTORY_HINT.search(line):
                    new_lines.append(raw)
                    continue
                new_line, edits = replace_line(line, live)
                if edits:
                    rel = os.path.relpath(path, args.repo_root)
                    for old, value in edits:
                        file_edits.append(f"  {rel}:{i + 1}  {old} -> {value}")
                    nl = raw[len(line):]
                    new_lines.append(new_line + nl)
                else:
                    new_lines.append(raw)
            if not file_edits:
                continue
            changed_files += 1
            total_edits += len(file_edits)
            for e in file_edits:
                print(e)
            if not args.dry_run:
                with open(path, "w", encoding="utf-8", newline="") as f:
                    f.writelines(new_lines)

    print()
    print(f"{changed_files} files, {total_edits} number(s) "
          f"{'would be' if args.dry_run else ''} updated.")
    if not args.dry_run:
        stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
        record = {"as_of_utc": stamp, "source": ENDPOINT, **live}
        out = os.path.abspath(os.path.join(os.path.dirname(__file__), "..",
                                           "catalog-claims.json"))
        with open(out, "w", encoding="utf-8") as f:
            json.dump(record, f, indent=2)
            f.write("\n")
        print(f"Wrote {out}")
    print("Next: python3 scripts/verify_claims.py --repo-root <root> && git diff")
    return 0


if __name__ == "__main__":
    sys.exit(main())
